import { useCallback, useLayoutEffect, useRef } from "react";

/**
 * Обработчик с неизменной ссылкой, всегда вызывающий свежее замыкание.
 *
 * Статус эфира опрашивается раз в секунду и перерисовывает всё дерево
 * приложения. Обычная функция, объявленная в теле компонента, при каждой такой
 * перерисовке получает новую идентичность и тянет за собой `memo`-поддеревья:
 * тяжёлые экраны перерисовываются секунда за секундой, а открытый селектор или
 * поле ввода теряют состояние прямо под руками оператора.
 *
 * Ссылка здесь создаётся один раз, а тело подменяется после каждого рендера,
 * поэтому устаревшего замыкания не возникает и список зависимостей не нужен.
 */
export function useStableCallback<Args extends unknown[], Result>(
  callback: (...args: Args) => Result,
): (...args: Args) => Result {
  const latest = useRef(callback);
  useLayoutEffect(() => {
    latest.current = callback;
  });
  return useCallback((...args: Args) => latest.current(...args), []);
}
